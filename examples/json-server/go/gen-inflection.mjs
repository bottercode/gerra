// Generates inflection_rules.go from the `inflection` package json-server uses, so the Go port
// pluralizes and singularizes exactly like the original. Run: node gen-inflection.mjs
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const jsonServer = require.resolve("json-server/package.json", { paths: [join(import.meta.dirname, "..")] });
const lib = createRequire(jsonServer).resolve("inflection");
const version = JSON.parse(readFileSync(join(lib, "../../package.json"), "utf8")).version;
// The rule tables aren't exported; load a copy of the (CommonJS) module that exports them too.
const src = readFileSync(lib, "utf8") + "\nmodule.exports.__plural = pluralRules; module.exports.__singular = singularRules; module.exports.__uncountable = uncountableWords;\n";
const tmp = join(mkdtempSync(join(tmpdir(), "inflection-")), "inflection.cjs");
writeFileSync(tmp, src);
const m = require(tmp);

const goRegex = (re) => {
  if (!["g", "gi"].includes(re.flags)) throw new Error(`unexpected flags ${re.flags}`);
  return (re.flags.includes("i") ? "(?i)" : "") + re.source;
};
// JS "$1" → Go "${1}" (Go would read "$1s" as a group named "1s").
const goReplacement = (r) => r.replace(/\$(\d)/g, "$${$1}");
const rule = ([re, rep]) => `\t{regexp.MustCompile(${JSON.stringify(goRegex(re))}), ${rep === undefined ? "false" : "true"}, ${JSON.stringify(rep === undefined ? "" : goReplacement(rep))}},`;

writeFileSync(
  join(import.meta.dirname, "inflection_rules.go"),
  `// Code generated by gen-inflection.mjs from inflection@${version}; DO NOT EDIT.

package main

import "regexp"

var uncountableWords = map[string]bool{
${m.__uncountable.map((w) => `\t${JSON.stringify(w)}: true,`).join("\n")}
}

var pluralRules = []inflectionRule{
${m.__plural.map(rule).join("\n")}
}

var singularRules = []inflectionRule{
${m.__singular.map(rule).join("\n")}
}
`,
);
execFileSync("gofmt", ["-w", join(import.meta.dirname, "inflection_rules.go")]);
console.log(`inflection_rules.go: ${m.__plural.length} plural and ${m.__singular.length} singular rules, ${m.__uncountable.length} uncountable words (inflection@${version})`);
